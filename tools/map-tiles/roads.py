"""The intercity roads for @driver/map/pieces/road: each Aziziyah garage → Baghdad (كراج النهضة) and → Kut, the fastest
way by road class over the Overture segments in data/w_segment.json, simplified to 8 m. Writes
packages/map/src/golden/road-data.ts. Run from the repo root: python3 tools/map-tiles/roads.py"""
import heapq, json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'packages', 'map', 'src', 'golden', 'road-data.ts')
# Garages as in apps/api/src/modules/routes/intercity.config.ts (lng, lat).
GARAGES = {'bab1': (45.0405, 32.91575), 'bab2': (45.0641, 32.9155), 'souq': (45.0666, 32.9021)}
CITIES = {'baghdad': (44.4165, 33.3344), 'kut': (45.8189, 32.5126)}
# Metres cost more on smaller roads, so the route keeps to the highway the cars take.
PENALTY = {'motorway': 1, 'trunk': 1, 'primary': 1.05, 'secondary': 1.3, 'tertiary': 1.8,
           'unclassified': 2.2, 'residential': 2.5, 'service': 4}


def metres(a, b):
    return math.hypot((a[0] - b[0]) * math.cos(math.radians(33)) * 111320, (a[1] - b[1]) * 110540)


def graph():
    g = {}
    for f in json.load(open(os.path.join(HERE, 'data', 'w_segment.json')))['features']:
        cls = f['properties'].get('class')
        if cls not in PENALTY or f['geometry']['type'] != 'LineString':
            continue
        pts = [(round(x, 5), round(y, 5)) for x, y in f['geometry']['coordinates']]
        for a, b in zip(pts, pts[1:]):
            w = metres(a, b) * PENALTY[cls]
            g.setdefault(a, []).append((b, w))
            g.setdefault(b, []).append((a, w))
    return g


def route(g, nodes, a, b):
    s = min(nodes, key=lambda q: metres(a, q))
    t = min(nodes, key=lambda q: metres(b, q))
    dist, prev, heap = {s: 0}, {}, [(0, s)]
    while heap:
        d, u = heapq.heappop(heap)
        if u == t:
            break
        if d > dist[u]:
            continue
        for v, w in g[u]:
            if d + w < dist.get(v, 1e18):
                dist[v], prev[v] = d + w, u
                heapq.heappush(heap, (d + w, v))
    path = [t]
    while path[-1] != s:
        path.append(prev[path[-1]])
    return path[::-1]


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    xy = lambda p: (p[0] * math.cos(math.radians(33)) * 111320, p[1] * 110540)
    a, b = xy(pts[0]), xy(pts[-1])
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = math.hypot(dx, dy) or 1
    best, bi = 0, 0
    for i in range(1, len(pts) - 1):
        p = xy(pts[i])
        d = abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / length
        if d > best:
            best, bi = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[:bi + 1], tol)[:-1] + simplify(pts[bi:], tol)


def main():
    g = graph()
    nodes = list(g)
    lines = ['/**',
             ' * The real roads from each Aziziyah garage to Baghdad (كراج النهضة) and to Kut, generated by',
             ' * `tools/map-tiles/roads.py` from the Overture road network (fastest by road class: trunk and primary first),',
             ' * simplified to 8 m. Re-generate when a garage moves; field ops check the roads on the ground.',
             ' */',
             "import type { LngLat } from './metres.js';",
             '',
             'export const ROAD_PATHS: Record<string, readonly LngLat[]> = {']
    for gid, gp in GARAGES.items():
        for cid, cp in CITIES.items():
            pts = [[round(x, 5), round(y, 5)] for x, y in simplify(route(g, nodes, gp, cp), 8)]
            lines.append(f"  '{gid}-{cid}': {json.dumps(pts, separators=(',', ':'))},")
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
