# Writes packages/map/src/golden/garage-bays.ts: where the cars stand in the three 3D garages (landmarks.py), so a screen
# can float each departure's seats over its own car (N12, Ali 2026-10-11). Run after changing the garage model:
#   python3 tools/map-tiles/garage_bays.py
import math, os
import shapely.affinity as af, shapely.geometry as sg
from landmarks import SITES, GARAGE_SIZE

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'packages', 'map', 'src', 'golden', 'garage-bays.ts')
lat0 = 32.9; mx = 111320 * math.cos(math.radians(lat0)); my = 110540
SEED = {'garage_bab1': 0, 'garage_bab2': 2, 'garage_souq': 4}


def bays(key):
    """The occupied bays of garage() in its local frame, the same loop as the model draws them."""
    W, D = GARAGE_SIZE[key]; seed = SEED[key]
    hw = W / 2; f = -D / 2
    ys0, ys1 = f + 14.5, D / 2 - 2
    xs0, xs1 = -hw + 3, hw - 3
    ym = (ys0 + ys1) / 2
    nb = int((xs1 - xs0 - 2) / 3.6)
    out = []
    for row, yb in enumerate((ym - 4.7, ym + 4.7)):
        for i in range(nb):
            if (i * 3 + row * 5 + seed) % 6 != 2:
                out.append((xs0 + 2.8 + i * 3.6, yb, row))
    return out


lines = []
for key, (lng, lat, ang, side) in SITES.items():
    if not key.startswith('garage_'): continue
    rot = ang if side > 0 else ang + 180
    cx, cy = lng * mx, lat * my
    pts = []
    for x, y, row in bays(key):
        p = af.translate(af.rotate(sg.Point(x, y), rot, origin=(0, 0)), cx, cy)
        # the cars stand across the row facing the middle island: row 0 faces local +y, row 1 faces -y
        br = (-rot + (0 if row == 0 else 180)) % 360
        pts.append(f'{{ at: [{p.x / mx:.6f}, {p.y / my:.6f}], bearing: {br:.0f} }}')
    lines.append(f"  {key.split('_')[1]}: [\n    " + ',\n    '.join(pts) + ',\n  ],')

src = f"""// Generated by tools/map-tiles/garage_bays.py from the garage model in landmarks.py; do not edit by hand.
import type {{ GarageKey }} from './garage-seats.js';

/** Where each car stands in the three 3D garages, in bay order (row by the hall first, then the far row). */
export const GARAGE_BAYS: Record<GarageKey, readonly {{ at: [number, number]; bearing: number }}[]> = {{
{chr(10).join(lines)}
}};
"""
open(OUT, 'w').write(src)
print('wrote', OUT)
